#!/usr/bin/env python3

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(
        description="Generate a repeated OPALX FODO lattice."
    )
    parser.add_argument(
        "--cells",
        type=int,
        required=True,
        help="Number of FODO cells",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output OPALX include file",
    )

    args = parser.parse_args()

    if args.cells < 1:
        raise ValueError("Number of cells must be positive.")

    lines = [
        "// ------------------------------------------------------------",
        "// Auto-generated FODO lattice",
        f"// Number of cells: {args.cells}",
        "// Generated by generate_fodo_lattice.py",
        "// ------------------------------------------------------------",
        "",
    ]

    members = []

    for i in range(args.cells):
        cell = i + 1

        qf = f"QF_{cell:03d}"
        d1 = f"D1_{cell:03d}"
        qd = f"QD_{cell:03d}"
        d2 = f"D2_{cell:03d}"

        s0 = f"{i}*Lcell"

        lines.append(
            f"{qf}: QUADRUPOLE, "
            f"L=LQ, K1=k1, "
            f"ELEMEDGE={s0};"
        )

        lines.append(
            f"{d1}: DRIFT, "
            f"L=LD, "
            f"ELEMEDGE={s0}+LQ;"
        )

        lines.append(
            f"{qd}: QUADRUPOLE, "
            f"L=LQ, K1=-k1, "
            f"ELEMEDGE={s0}+LQ+LD;"
        )

        lines.append(
            f"{d2}: DRIFT, "
            f"L=LD, "
            f"ELEMEDGE={s0}+2.0*LQ+LD;"
        )

        lines.append("")

        members.extend([qf, d1, qd, d2])

    line_name = f"FODO{args.cells}"

    lines.append(f"{line_name}: LINE=(")

    for j, member in enumerate(members):
        comma = "," if j < len(members) - 1 else ""
        lines.append(f"    {member}{comma}")

    lines.append(");")
    lines.append("")

    args.output.write_text("\n".join(lines))

    print(f"Generated {args.output}")
    print(f"Cells:        {args.cells}")
    print(f"Elements:     {4 * args.cells}")
    print(f"OPALX line:   {line_name}")


if __name__ == "__main__":
    main()